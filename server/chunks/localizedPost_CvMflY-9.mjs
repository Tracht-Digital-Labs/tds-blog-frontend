/** One shortcode paragraph as markdown renders it, with any attributes on `<p>`. */
var SHORTCODE = /<p\b[^>]*>\s*\{\{\s*(?:produkt|product):([a-z0-9-]{2,120})(?:\s+(card|inline|list))?\s*\}\}\s*<\/p>/g;
/** Split rendered HTML into prose parts and product embeds, in order. */
function splitProductShortcodes(html) {
	const parts = [];
	let last = 0;
	for (const match of html.matchAll(SHORTCODE)) {
		const before = html.slice(last, match.index);
		if (before.trim() !== "") parts.push({
			kind: "html",
			html: before
		});
		parts.push({
			kind: "product",
			slug: match[1],
			variant: match[2] ?? "card"
		});
		last = match.index + match[0].length;
	}
	const rest = html.slice(last);
	if (rest.trim() !== "") parts.push({
		kind: "html",
		html: rest
	});
	return parts;
}
